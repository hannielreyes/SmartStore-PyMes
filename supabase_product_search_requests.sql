-- Solicitudes de productos no encontrados.
-- Ejecutar una vez en Supabase SQL Editor.
create table if not exists public.solicitudes_productos (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null references public.usuarios(id) on delete cascade,
    termino text not null,
    creado_en timestamptz not null default now(),
    atendida boolean not null default false
);

create index if not exists idx_solicitudes_productos_estado
    on public.solicitudes_productos (atendida, creado_en desc);
create index if not exists idx_solicitudes_productos_usuario
    on public.solicitudes_productos (usuario_id);
