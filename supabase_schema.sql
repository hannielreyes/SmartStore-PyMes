-- Esquema inicial compartido de SmartStore para Supabase/PostgreSQL.
-- Ejecutar en Supabase SQL Editor antes de migrar la capa database.py.

create table if not exists public.usuarios (
    id bigint generated by default as identity primary key,
    nombre text,
    correo text not null unique,
    telefono text,
    fecha_nacimiento date,
    contraseña text,
    codigo_sesion text,
    auth_user_id uuid unique,
    paypal_email text,
    imagen text
);

create table if not exists public.sesiones_dispositivo (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null references public.usuarios(id) on delete cascade,
    token_hash text not null unique,
    creado_en timestamptz not null default now(),
    revocado boolean not null default false
);

create table if not exists public.tiendas (
    id bigint generated by default as identity primary key,
    nombre text not null,
    whatsapp text,
    tasa_cambio numeric(12, 4),
    usuario_id bigint not null references public.usuarios(id) on delete cascade,
    direccion text,
    saldo numeric(14, 2) not null default 0,
    imagen text,
    constraint una_tienda_por_usuario unique (usuario_id)
);

create table if not exists public.productos (
    id bigint generated by default as identity primary key,
    nombre text not null,
    marca text,
    talla text,
    precio_cordobas numeric(14, 2),
    precio_dolares numeric(14, 2),
    stock integer not null default 0 check (stock >= 0),
    tienda_id bigint not null references public.tiendas(id) on delete cascade,
    imagen text,
    categoria text not null default 'General',
    imagen_2 text,
    descripcion text,
    estado_producto text default 'Nuevo',
    etiquetas text,
    estilo text,
    color_principal text,
    material text,
    garantia text,
    especificacion text
);

create table if not exists public.reservas (
    id bigint generated by default as identity primary key,
    usuario_id bigint references public.usuarios(id) on delete cascade,
    producto_id bigint references public.productos(id) on delete cascade,
    cantidad integer not null check (cantidad > 0),
    fecha timestamptz not null default now(),
    estado text not null default 'Reservado',
    fecha_entrega timestamptz,
    tienda_id bigint references public.tiendas(id) on delete cascade,
    order_id text unique,
    fecha_expiracion timestamptz
);

create table if not exists public.resenas (
    id bigint generated by default as identity primary key,
    producto_id bigint references public.productos(id) on delete cascade,
    usuario_id bigint references public.usuarios(id) on delete set null,
    calificacion integer not null check (calificacion between 1 and 5),
    comentario text,
    fecha timestamptz not null default now()
);

create index if not exists idx_tiendas_usuario_id on public.tiendas(usuario_id);
create index if not exists idx_productos_tienda_id on public.productos(tienda_id);
create index if not exists idx_productos_nombre on public.productos(nombre);
create index if not exists idx_reservas_usuario_id on public.reservas(usuario_id);
create index if not exists idx_reservas_tienda_id on public.reservas(tienda_id);
create index if not exists idx_reservas_estado on public.reservas(estado);
create index if not exists idx_reservas_expiracion on public.reservas(fecha_expiracion);
create index if not exists idx_resenas_producto_id on public.resenas(producto_id);
create index if not exists idx_sesiones_usuario_id on public.sesiones_dispositivo(usuario_id);
create index if not exists idx_sesiones_token_activo on public.sesiones_dispositivo(token_hash, revocado);

