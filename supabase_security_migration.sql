ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS codigo_sesion text;
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS auth_user_id uuid UNIQUE;

CREATE TABLE IF NOT EXISTS public.sesiones_dispositivo (
	id bigint generated by default as identity primary key,
	usuario_id bigint not null references public.usuarios(id) on delete cascade,
	token_hash text not null unique,
	creado_en timestamptz not null default now(),
	revocado boolean not null default false
);

CREATE INDEX IF NOT EXISTS idx_sesiones_usuario_id
	ON public.sesiones_dispositivo(usuario_id);
CREATE INDEX IF NOT EXISTS idx_sesiones_token_activo
	ON public.sesiones_dispositivo(token_hash, revocado);

-- Crea el perfil de SmartStore automáticamente al crear una identidad Auth.
-- Así los datos del formulario llegan a Supabase aunque el correo requiera
-- confirmación y todavía no exista un access_token en la aplicación.
CREATE OR REPLACE FUNCTION public.crear_perfil_desde_auth()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
	INSERT INTO public.usuarios (
		auth_user_id, nombre, correo, telefono, fecha_nacimiento, imagen, paypal_email
	)
	VALUES (
		NEW.id,
		COALESCE(NEW.raw_user_meta_data->>'nombre', NEW.email),
		NEW.email,
		NEW.raw_user_meta_data->>'telefono',
		NULLIF(NEW.raw_user_meta_data->>'fecha_nacimiento', '')::date,
		NEW.raw_user_meta_data->>'imagen',
		'sb-zfl8251875274@business.example.com'
	)
	ON CONFLICT (auth_user_id) DO UPDATE SET
		correo = EXCLUDED.correo,
		nombre = COALESCE(EXCLUDED.nombre, public.usuarios.nombre),
		telefono = COALESCE(EXCLUDED.telefono, public.usuarios.telefono),
		fecha_nacimiento = COALESCE(EXCLUDED.fecha_nacimiento, public.usuarios.fecha_nacimiento),
		imagen = COALESCE(EXCLUDED.imagen, public.usuarios.imagen);
	RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS crear_perfil_auth_trigger ON auth.users;
CREATE TRIGGER crear_perfil_auth_trigger
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.crear_perfil_desde_auth();